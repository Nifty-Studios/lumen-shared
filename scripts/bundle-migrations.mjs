// Turns drizzle/{client,server} SQL migrations into src/schema/migrations.ts, so every
// consumer (Vite, Metro, Bun) can import them without raw-file loaders.
// Run via `pnpm db:generate` (or `pnpm db:bundle` after hand-editing a .sql file).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function load(dir) {
  const journal = JSON.parse(readFileSync(join(root, "drizzle", dir, "meta/_journal.json"), "utf8"));
  return journal.entries.map(({ tag }) => ({
    tag,
    statements: readFileSync(join(root, "drizzle", dir, `${tag}.sql`), "utf8")
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  }));
}

const out = `// GENERATED by scripts/bundle-migrations.mjs from drizzle/. Do not edit.

export interface Migration {
  tag: string;
  statements: string[];
}

export const clientMigrations: Migration[] = ${JSON.stringify(load("client"), null, 2)};

export const serverMigrations: Migration[] = ${JSON.stringify(load("server"), null, 2)};
`;

writeFileSync(join(root, "src/schema/migrations.ts"), out);
console.log("wrote src/schema/migrations.ts");
