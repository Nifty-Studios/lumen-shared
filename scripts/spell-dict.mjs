// Turns the English Hunspell dictionaries (dictionary-en and dictionary-en-gb, from SCOWL:
// MIT/BSD) into src/spell/en-us.ts and en-gb.ts, so Vite and the mobile bundles can load them
// without file loaders. Run via `pnpm spell-dict` after updating either package.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
for (const [pkg, out] of [["dictionary-en", "en-us"], ["dictionary-en-gb", "en-gb"]]) {
  const dir = join(root, "node_modules", pkg);
  const aff = readFileSync(join(dir, "index.aff"), "utf8");
  const dic = readFileSync(join(dir, "index.dic"), "utf8");
  writeFileSync(
    join(root, `src/spell/${out}.ts`),
    `// GENERATED by scripts/spell-dict.mjs from ${pkg} (SCOWL, MIT/BSD). Do not edit.\n\nexport const aff = ${JSON.stringify(aff)};\nexport const dic = ${JSON.stringify(dic)};\n`,
  );
  console.log(`wrote src/spell/${out}.ts (${Math.round((aff.length + dic.length) / 1024)} KB)`);
}
