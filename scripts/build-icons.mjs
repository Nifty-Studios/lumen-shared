const names = [...new Set([...UI, ...PAGE])].sort();
const missing = names.filter((n) => !existsSync(join(iconsDir, `${n}.mjs`)));
if (missing.length) {
  console.error("Unknown Lucide icons:", missing.join(", "));
  process.exit(1);
}

const nodes = {};
for (const name of names) nodes[name] = (await import(pathToFileURL(join(iconsDir, `${name}.mjs`)).href)).default;

const out = `// Generated by scripts/build-icons.mjs from Lucide (https://lucide.dev, ISC license). Do not edit.
// Each icon is a list of [tag, attributes] drawn in a 24x24 viewBox with a round 2px stroke.

export type IconNode = [tag: string, attrs: Record<string, string>][];

export const ICON_NODES = ${JSON.stringify(nodes)} as unknown as Record<IconName, IconNode>;

export const ICON_NAMES = ${JSON.stringify(names)} as const;
export type IconName = (typeof ICON_NAMES)[number];

/** Icons offered in the page icon picker, in picker order. */
export const PAGE_ICON_NAMES = ${JSON.stringify(PAGE)} as const satisfies readonly IconName[];
`;
writeFileSync(new URL("../src/icons/data.ts", import.meta.url), out);
console.log(`wrote ${names.length} icons`);
